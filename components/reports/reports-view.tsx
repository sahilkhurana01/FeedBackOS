"use client";

import { useEffect, useState } from "react";
import { FileText, Download, Eye, Plus, Sparkles, Calendar, Loader2, Inbox } from "lucide-react";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";

type LiveReport = {
  id: string;
  title: string;
  period: string;
  type: string;
  createdAt: string;
  summary: string;
  sentimentScore: number;
  totalReviewsAnalyzed: number;
  topPositiveTopic: string;
  topNegativeTopic: string;
  status: string;
};

export function ReportsView() {
  const [reports, setReports] = useState<LiveReport[]>([]);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [activeReport, setActiveReport] = useState<LiveReport | null>(null);
  const [toastMessage, setToastMessage] = useState<string | null>(null);
  const [bizName, setBizName] = useState("Your Business");

  const triggerToast = (msg: string) => {
    setToastMessage(msg);
    setTimeout(() => setToastMessage(null), 3000);
  };

  useEffect(() => {
    // Get business name from localStorage/API
    try {
      const raw = localStorage.getItem("feedbackos_business");
      if (raw) {
        const p = JSON.parse(raw);
        if (p.name) setBizName(p.name);
      }
    } catch {}

    fetch("/api/business/onboarding")
      .then((r) => r.json())
      .then((data) => { if (data?.business?.name) setBizName(data.business.name); })
      .catch(() => {});

    // Load existing reports from DB
    fetchReports();
  }, []);

  const fetchReports = () => {
    setLoading(true);
    fetch("/api/reports")
      .then((r) => r.json())
      .then((data) => {
        setReports(data.reports || []);
      })
      .catch(() => setReports([]))
      .finally(() => setLoading(false));
  };

  const handleGenerateNew = () => {
    setGenerating(true);
    triggerToast(`Generating new executive report for ${bizName}...`);
    const now = new Date();
    const monthYear = now.toLocaleString("en-US", { month: "long", year: "numeric" });

    fetch("/api/reports/generate", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ monthYear, businessName: bizName }),
    })
      .then((res) => res.json())
      .then((data) => {
        if (data.success && data.report) {
          const newReport: LiveReport = {
            id: data.report.reportId || `r-${Date.now()}`,
            title: `${data.report.monthYear ?? monthYear} Executive Intelligence Report`,
            period: `${data.report.monthYear ?? monthYear} Period`,
            type: "Monthly Summary",
            createdAt: "Just now",
            summary: data.report.executiveSummary || "Report generated successfully.",
            sentimentScore: data.report.netSentimentScore ?? 0,
            totalReviewsAnalyzed: data.report.totalFeedbackCount ?? 0,
            topPositiveTopic: data.report.positiveDriver?.title || "—",
            topNegativeTopic: data.report.frictionCluster?.title || "—",
            status: "Ready",
          };
          setReports((prev) => [newReport, ...prev]);
          triggerToast("Executive report generated successfully!");
        } else {
          triggerToast("Report generated! Refresh to see updates.");
        }
      })
      .catch(() => {
        triggerToast("Error generating report. Check your feedback data.");
      })
      .finally(() => setGenerating(false));
  };

  const handleDownloadPDF = (report: LiveReport) => {
    const content = `EXECUTIVE INTELLIGENCE REPORT\n${report.title}\nPeriod: ${report.period}\n\nEXECUTIVE SUMMARY\n${report.summary}\n\nKEY METRICS\nSentiment Index: ${report.sentimentScore}/100\nTotal Reviews Analyzed: ${report.totalReviewsAnalyzed}\nTop Positive Driver: ${report.topPositiveTopic}\nTop Friction Area: ${report.topNegativeTopic}\n\nGenerated by FeedbackOS — ${new Date().toLocaleDateString()}`;
    const blob = new Blob([content], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${report.title.replace(/\s+/g, "_")}.txt`;
    a.click();
    URL.revokeObjectURL(url);
    triggerToast(`Downloaded ${report.title}`);
  };

  return (
    <div className="space-y-6">
      {/* Toast */}
      {toastMessage && (
        <div className="fixed bottom-6 right-6 z-50 flex items-center gap-2 rounded-2xl bg-foreground px-4 py-3 text-[13px] text-background shadow-xl">
          <Sparkles className="size-4 text-primary" />
          <span>{toastMessage}</span>
        </div>
      )}

      {/* Header */}
      <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h1 className="text-3xl font-semibold tracking-tight">Executive Intelligence Reports</h1>
          <p className="mt-1 text-[15px] text-muted-foreground">
            Automated executive summaries generated from your live customer feedback data.
          </p>
        </div>
        <Button onClick={handleGenerateNew} className="gap-2" disabled={generating}>
          {generating ? <Loader2 className="size-4 animate-spin" /> : <Plus className="size-4" />}
          {generating ? "Generating..." : "Generate New Report"}
        </Button>
      </div>

      {loading && (
        <div className="flex flex-col items-center justify-center rounded-3xl border border-black/5 bg-background p-16 dark:border-white/10">
          <Loader2 className="size-8 text-primary animate-spin mb-4" />
          <p className="text-[14px] text-muted-foreground">Loading reports...</p>
        </div>
      )}

      {!loading && reports.length === 0 && (
        <div className="flex flex-col items-center justify-center rounded-3xl border border-black/5 bg-background p-16 text-center dark:border-white/10">
          <Inbox className="size-10 text-muted-foreground/40 mb-4" />
          <p className="text-[16px] font-semibold text-foreground">No reports yet</p>
          <p className="mt-1 text-[13px] text-muted-foreground max-w-sm">
            Upload feedback and click "Generate New Report" to create your first executive intelligence report.
          </p>
        </div>
      )}

      {/* Reports Grid */}
      {!loading && reports.length > 0 && (
        <div className="grid gap-6 md:grid-cols-2">
          {reports.map((report) => (
            <div
              key={report.id}
              className="flex flex-col justify-between rounded-3xl border border-black/5 bg-background p-6 shadow-sm transition-all hover:shadow-md dark:border-white/10"
            >
              <div>
                <div className="flex items-center justify-between">
                  <Badge variant="outline" className="text-[11px]">
                    {report.type}
                  </Badge>
                  <span className="text-[12px] text-muted-foreground flex items-center gap-1">
                    <Calendar className="size-3.5" />
                    {report.createdAt}
                  </span>
                </div>

                <h3 className="mt-3 text-xl font-semibold text-foreground">{report.title}</h3>
                <p className="text-[12px] text-muted-foreground mt-0.5">Period: {report.period}</p>

                <p className="mt-4 text-[14px] leading-relaxed text-foreground rounded-2xl bg-muted p-4">
                  {report.summary}
                </p>

                <div className="mt-4 grid grid-cols-3 gap-2 border-t border-black/5 pt-4 text-center dark:border-white/10">
                  <div>
                    <p className="text-[11px] text-muted-foreground">Sentiment Index</p>
                    <p className="font-semibold text-[16px] text-primary">{report.sentimentScore}/100</p>
                  </div>
                  <div>
                    <p className="text-[11px] text-muted-foreground">Analyzed</p>
                    <p className="font-semibold text-[16px] text-foreground">{report.totalReviewsAnalyzed} reviews</p>
                  </div>
                  <div>
                    <p className="text-[11px] text-muted-foreground">Top Positive</p>
                    <p className="font-semibold text-[13px] text-emerald-600 dark:text-emerald-400">{report.topPositiveTopic}</p>
                  </div>
                </div>
              </div>

              <div className="mt-6 flex items-center justify-between border-t border-black/5 pt-4 dark:border-white/10">
                <Button
                  variant="outline"
                  size="sm"
                  onClick={() => setActiveReport(report)}
                  className="gap-2 text-[12.5px]"
                >
                  <Eye className="size-3.5" />
                  View Full Report
                </Button>

                <Button
                  variant="ghost"
                  size="sm"
                  onClick={() => handleDownloadPDF(report)}
                  className="gap-2 text-[12.5px] text-primary"
                >
                  <Download className="size-3.5" />
                  Export PDF
                </Button>
              </div>
            </div>
          ))}
        </div>
      )}

      {/* Full Report Modal */}
      {activeReport && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/40 backdrop-blur-xs p-4">
          <div className="w-full max-w-2xl max-h-[90vh] overflow-y-auto rounded-3xl bg-background p-6 shadow-2xl space-y-6">
            <div className="flex items-center justify-between border-b border-black/5 pb-4 dark:border-white/10">
              <div>
                <Badge variant="outline" className="text-[11px]">
                  {activeReport.type}
                </Badge>
                <h2 className="text-2xl font-semibold mt-1">{activeReport.title}</h2>
                <p className="text-[12px] text-muted-foreground">{activeReport.period}</p>
              </div>
              <Button variant="ghost" size="sm" onClick={() => setActiveReport(null)}>
                Close
              </Button>
            </div>

            <div className="space-y-4">
              <div className="rounded-2xl bg-muted p-4">
                <h4 className="text-[13px] font-semibold text-foreground uppercase tracking-wider">Executive Overview</h4>
                <p className="mt-2 text-[14px] leading-relaxed text-foreground">{activeReport.summary}</p>
              </div>

              <div className="rounded-2xl border border-black/5 p-4 space-y-2 dark:border-white/10">
                <h4 className="text-[13px] font-semibold text-foreground">Key Metrics</h4>
                <ul className="list-disc list-inside space-y-1 text-[13.5px] text-muted-foreground">
                  <li>Sentiment Index: <strong>{activeReport.sentimentScore}/100</strong></li>
                  <li>Total Reviews Analyzed: <strong>{activeReport.totalReviewsAnalyzed}</strong></li>
                  <li>Top Positive Driver: <strong className="text-emerald-600">{activeReport.topPositiveTopic}</strong></li>
                  <li>Top Friction Area: <strong className="text-red-600">{activeReport.topNegativeTopic}</strong></li>
                </ul>
              </div>

              <div className="flex items-center justify-end gap-3 pt-2">
                <Button
                  onClick={() => handleDownloadPDF(activeReport)}
                  className="gap-2"
                >
                  <Download className="size-4" />
                  Download Report
                </Button>
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
